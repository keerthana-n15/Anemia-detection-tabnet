# ---- Confusion Matrix with Error Highlighting ----
def plot_confusion_matrix_with_errors(y_true, y_pred, labels=None, title="Confusion Matrix with Errors"):
    cm = confusion_matrix(y_true, y_pred)

    plt.figure(figsize=(6,5))
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                xticklabels=labels, yticklabels=labels,
                cbar=False, linewidths=1, linecolor="gray")

    # Overlay errors in red
    for i in range(len(cm)):
        for j in range(len(cm)):
            if i != j and cm[i,j] > 0:  # only errors
                plt.text(j+0.5, i+0.5, f"{cm[i,j]}",
                         ha="center", va="center", color="red", fontsize=14, fontweight="bold")

    plt.title(title)
    plt.ylabel("True Label")
    plt.xlabel("Predicted Label")
    plt.show()

